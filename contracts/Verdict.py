def _now_ts() -> int:
    return int(datetime.now(timezone.utc).timestamp())


def _sender() -> str:
    return str(gl.message.sender_address)


CHALLENGE_WINDOW_SECONDS = 600


class ClaimPosted(gl.chain.Event):
    def __init__(self, claim_id: str, claimant: Address, /): ...


class ClaimChallenged(gl.chain.Event):
    def __init__(self, challenger: Address, claim_id: str, /): ...


class ClaimResolved(gl.chain.Event):
    def __init__(self, claim_id: str, outcome: str, /): ...


class Verdict(gl.contract.Contract):
    claims: TreeMap[str, str]       # claim_id -> json claim record
    claimable: TreeMap[str, u256]   # address  -> owed balance (wei)
    claim_counter: u256
    treasury: str
    min_claim_bond: u256
    min_challenge_bond: u256
    protocol_fee_bps: u256
    challenge_window: u256

    def __init__(self, treasury: str, challenge_window_seconds: str = ""):
        self.treasury = Address(treasury).as_hex
        self.min_claim_bond = u256(MIN_CLAIM_BOND)
        self.min_challenge_bond = u256(MIN_CHALLENGE_BOND)
        self.protocol_fee_bps = u256(PROTOCOL_FEE_BPS)
        window = CHALLENGE_WINDOW_SECONDS
        if challenge_window_seconds not in (None, ""):
            try:
                window = max(0, int(str(challenge_window_seconds)))
            except ValueError:
                window = CHALLENGE_WINDOW_SECONDS
        self.challenge_window = u256(window)

    # -- helpers -------------------------------------------------------------

    def _load(self, claim_id: str) -> dict:
        raw = self.claims.get(str(claim_id).strip().upper())
        if raw is None:
            raise gl.vm.UserError(ERRORS["CLAIM_MISSING"])
        return json.loads(raw)

    def _save(self, rec: dict) -> None:
        self.claims[rec["claim_id"]] = json.dumps(rec)

    def _credit(self, addr: str, amount: int) -> None:
        if not addr or amount <= 0:
            return
        current = int(self.claimable.get(addr, u256(0)))
        self.claimable[addr] = u256(current + amount)

    # -- writes --------------------------------------------------------------

    @gl.public.write.payable
    def post_claim(self, title: str, statement: str, evidence_urls: str) -> str:
        """Posts a claim. Attached GEN is the claimant's bond (>= min_claim_bond).
        `evidence_urls` is a JSON array of 1-4 public https urls."""
        try:
            t = validate_title(title)
            s = validate_statement(statement)
            urls = validate_evidence_urls(evidence_urls)
            bond = validate_bond(gl.message.value, int(self.min_claim_bond))
        except VerdictValidationError as exc:
            raise gl.vm.UserError(ERRORS[exc.code])

        n = int(self.claim_counter) + 1
        self.claim_counter = u256(n)
        claim_id = make_claim_id(n)
        claimant = Address(_sender()).as_hex
        rec = {
            "claim_id": claim_id,
            "claimant": claimant,
            "title": t,
            "statement": s,
            "evidence_urls": urls,
            "state": STATE_OPEN,
            "opened_at": _now_ts(),
            "resolved_at": 0,
            "challenge_deadline": _now_ts() + int(self.challenge_window),
            "claimant_bond": str(bond),
            "challenger": "",
            "challenger_bond": "0",
            "challenge_note": "",
            "outcome": "",
            "confidence": 0,
            "reasoning": "",
            "key_facts": [],
            "evidence_report": [],
            "fee": "0",
        }
        self._save(rec)
        ClaimPosted(claim_id, Address(claimant)).emit()
        return claim_id

    @gl.public.write.payable
    def challenge(self, claim_id: str, note: str) -> None:
        """Bonds GEN against an open claim. One challenger per claim."""
        rec = self._load(claim_id)
        if rec["state"] != STATE_OPEN:
            raise gl.vm.UserError(ERRORS["NOT_OPEN"])
        if rec["challenger"]:
            raise gl.vm.UserError(ERRORS["ALREADY_CHALLENGED"])
        who = Address(_sender()).as_hex
        if who == rec["claimant"]:
            raise gl.vm.UserError(ERRORS["SELF_CHALLENGE"])
        try:
            n = validate_note(note)
            bond = validate_bond(gl.message.value, int(self.min_challenge_bond))
        except VerdictValidationError as exc:
            raise gl.vm.UserError(ERRORS[exc.code])
        rec["challenger"] = who
        rec["challenger_bond"] = str(bond)
        rec["challenge_note"] = n
        self._save(rec)
        ClaimChallenged(Address(who), rec["claim_id"]).emit()

    @gl.public.write
    def withdraw_claim(self, claim_id: str) -> None:
        """Claimant takes back an unchallenged claim and its bond."""
        rec = self._load(claim_id)
        if rec["state"] != STATE_OPEN:
            raise gl.vm.UserError(ERRORS["NOT_OPEN"])
        if Address(_sender()).as_hex != rec["claimant"]:
            raise gl.vm.UserError(ERRORS["NOT_CLAIMANT"])
        if rec["challenger"]:
            raise gl.vm.UserError(ERRORS["HAS_CHALLENGER"])
        rec["state"] = STATE_RESOLVED
        rec["outcome"] = OUTCOME_UNRESOLVABLE
        rec["reasoning"] = "withdrawn by the claimant before resolution"
        rec["resolved_at"] = _now_ts()
        self._credit(rec["claimant"], int(rec["claimant_bond"]))
        self._save(rec)

    @gl.public.write
    def resolve(self, claim_id: str) -> str:
        """The single non-deterministic step. Permissionless. A challenged claim can
        be resolved at once; an unchallenged one only after the challenge window."""
        rec = self._load(claim_id)
        if rec["state"] != STATE_OPEN:
            raise gl.vm.UserError(ERRORS["NOT_OPEN"])
        if not rec["challenger"] and _now_ts() < int(rec["challenge_deadline"]):
            raise gl.vm.UserError("challenge window is still open")

        # Plain local copies: storage objects never cross into a nondet block.
        urls = list(rec["evidence_urls"])
        title = rec["title"]
        statement = rec["statement"]
        note = rec["challenge_note"]
        cid = rec["claim_id"]
        locked = set(urls)

        def leader_fn() -> str:
            records = []
            for url in urls:
                try:
                    page = gl.nondet.web.get(url)
                    body = getattr(page, "body", None)
                    if body is None:
                        body = str(page)
                    if isinstance(body, (bytes, bytearray)):
                        body = bytes(body).decode("utf-8", errors="replace")
                    status = getattr(page, "status", 200)
                except Exception:
                    body = ""
                    status = 0
                records.append(normalize_evidence(url, status, body))
            ok = evidence_is_sufficient(records)
            if not ok:
                verdict = canonicalize_verdict({}, evidence_ok=False)
            else:
                try:
                    raw = gl.nondet.exec_prompt(build_prompt(title, statement, note, records))
                except Exception:
                    raw = ""
                verdict = canonicalize_verdict(raw, evidence_ok=True)
            verdict["claim_id"] = cid
            verdict["evidence"] = [
                {k: r[k] for k in ("url", "status", "ok", "title", "limitations")}
                for r in records
            ]
            return json.dumps(verdict, sort_keys=True)

        def validator_fn(leader_result) -> bool:
            # The validator redoes the WHOLE job -- its own fetches, its own prompt,
            # its own canonicalization -- and compares two independent verdicts.
            payload = getattr(leader_result, "calldata", None)
            if payload is None:
                return False
            try:
                theirs = json.loads(str(payload))
            except (json.JSONDecodeError, TypeError):
                return False
            if not isinstance(theirs, dict):
                return False
            mine = json.loads(leader_fn())
            return verdicts_equivalent(theirs, mine)

        raw_result = gl.vm.run_nondet(leader_fn, validator_fn)
        try:
            agreed = json.loads(str(raw_result))
        except (json.JSONDecodeError, TypeError):
            agreed = {}
        if not isinstance(agreed, dict):
            agreed = {}

        binding = bind_envelope(agreed, cid, locked)
        if not binding["bound"]:
            verdict = canonicalize_verdict({}, evidence_ok=False)
        else:
            verdict = canonicalize_verdict(
                agreed, evidence_ok=any(e["ok"] for e in binding["records"])
            )

        rec = self._load(cid)
        if rec["state"] != STATE_OPEN:
            raise gl.vm.UserError(ERRORS["NOT_OPEN"])
        result = settle(
            verdict["outcome"], rec["claimant"], int(rec["claimant_bond"]),
            rec["challenger"], int(rec["challenger_bond"]), self.treasury,
            int(self.protocol_fee_bps),
        )
        for addr, amount in result["credits"].items():
            self._credit(addr, amount)
        rec["state"] = STATE_RESOLVED
        rec["outcome"] = verdict["outcome"]
        rec["confidence"] = verdict["confidence"]
        rec["reasoning"] = verdict["reasoning"]
        rec["key_facts"] = verdict["key_facts"]
        rec["evidence_report"] = binding["records"]
        rec["fee"] = str(result["fee"])
        rec["resolved_at"] = _now_ts()
        self._save(rec)
        ClaimResolved(cid, verdict["outcome"]).emit()
        return verdict["outcome"]

    @gl.public.write
    def claim_funds(self) -> u256:
        """The only method that moves GEN out of the contract: pays the caller their
        whole ledger balance."""
        sender = Address(_sender()).as_hex
        owed = int(self.claimable.get(sender, u256(0)))
        if owed <= 0:
            raise gl.vm.UserError(ERRORS["NOTHING_TO_CLAIM"])
        self.claimable[sender] = u256(0)
        gl.contract.get_at(gl.message.sender_address).emit_transfer(value=u256(owed))
        return u256(owed)

    # -- views ---------------------------------------------------------------

    @gl.public.view
    def get_config(self) -> str:
        return json.dumps({
            "treasury": self.treasury,
            "min_claim_bond": str(int(self.min_claim_bond)),
            "min_challenge_bond": str(int(self.min_challenge_bond)),
            "protocol_fee_bps": int(self.protocol_fee_bps),
            "challenge_window_seconds": int(self.challenge_window),
            "max_evidence_urls": MAX_EVIDENCE_URLS,
            "min_confidence": MIN_CONFIDENCE,
            "confidence_tolerance": CONFIDENCE_TOLERANCE,
            "claim_count": int(self.claim_counter),
        })

    @gl.public.view
    def list_claims(self) -> str:
        return json.dumps(sorted(k for k, _ in self.claims.items()))

    @gl.public.view
    def get_claim(self, claim_id: str) -> str:
        return json.dumps(self._load(claim_id))

    @gl.public.view
    def get_claimable(self, address: str) -> str:
        return str(int(self.claimable.get(Address(address).as_hex, u256(0))))
